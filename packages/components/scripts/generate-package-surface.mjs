import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { readTsupList } from "./tsup-entries.mjs";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const readmePath = join(packageRoot, "README.md");

const SECTION_HEADING = "## Current package surface";
/** The section ends where the next one begins. */
const NEXT_HEADING = "## Package status and test coverage";

const PACKAGE_NAME = "@zentauri-ui/zentauri-components";

/**
 * Rows of the surface table, in the order they are rendered.
 *
 * `list` names the `as const` array in `tsup.config.ts` that produces the
 * entries, so a row can never disagree with what the build actually emits.
 */
const SURFACES = [
  {
    label: "Static UI entries",
    list: "uiComponentNames",
    importShape: `${PACKAGE_NAME}/ui/<name>`,
  },
  {
    label: "Animated UI entries",
    list: "uiAnimatedComponentNames",
    importShape: `${PACKAGE_NAME}/ui/<name>/animated`,
  },
  {
    label: "Animation entries",
    list: "animationEntryNames",
    importShape: `${PACKAGE_NAME}/animations/<name>`,
  },
  {
    label: "Chart entries",
    list: "chartEntryNames",
    importShape: `${PACKAGE_NAME}/charts/<type>`,
  },
  {
    label: "Hook entries",
    list: "hooksEntryNames",
    importShape: `${PACKAGE_NAME}/hooks/<entry>`,
  },
];

/**
 * Count every published entry surface, plus the UI areas that ship motion only.
 *
 * @returns {{rows: {label: string, count: number, importShape: string}[], animatedOnly: string[]}}
 */
export function buildPackageSurface() {
  const lists = new Map(
    SURFACES.map((surface) => [surface.list, readTsupList(surface.list)]),
  );

  const staticUi = lists.get("uiComponentNames") ?? [];
  const animatedUi = lists.get("uiAnimatedComponentNames") ?? [];

  return {
    rows: SURFACES.map((surface) => ({
      label: surface.label,
      count: (lists.get(surface.list) ?? []).length,
      importShape: surface.importShape,
    })),
    animatedOnly: animatedUi.filter((name) => !staticUi.includes(name)),
  };
}

/**
 * Prose for the UI areas that exist only as an animated entry.
 *
 * Derived rather than written by hand: `spinner` has been the only one for a
 * while, but the sentence has to survive that changing.
 *
 * @param {string[]} animatedOnly Sorted area names with no static entry.
 * @returns {string} One Markdown paragraph.
 */
function animatedOnlyParagraph(animatedOnly) {
  if (animatedOnly.length === 0) {
    return "Every animated UI area also ships a static entry.";
  }

  if (animatedOnly.length === 1) {
    const name = animatedOnly[0];
    return `\`${name}\` is the only animated-only UI area. Import it from \`${PACKAGE_NAME}/ui/${name}/animated\`; there is no \`${PACKAGE_NAME}/ui/${name}\` static entry.`;
  }

  const quoted = animatedOnly.map((name) => `\`${name}\``);
  const list = `${quoted.slice(0, -1).join(", ")}, and ${quoted[quoted.length - 1]}`;
  return `${list} are animated-only UI areas. Import each from \`${PACKAGE_NAME}/ui/<name>/animated\`; they have no \`${PACKAGE_NAME}/ui/<name>\` static entry.`;
}

/**
 * Render the whole section, including its heading and trailing blank line.
 *
 * Column widths are computed so the table stays aligned as counts grow into
 * more digits. `README.md` is listed in `.prettierignore`, so this output is
 * the final formatting — nothing reflows it afterwards.
 *
 * @param {ReturnType<typeof buildPackageSurface>} surface
 * @returns {string} Markdown section text.
 */
export function renderPackageSurfaceSection(surface) {
  const labelWidth = Math.max(
    "Surface".length,
    ...surface.rows.map((row) => row.label.length),
  );
  const countWidth = Math.max(
    "Count".length,
    ...surface.rows.map((row) => String(row.count).length),
  );
  const importCells = surface.rows.map((row) => `\`${row.importShape}\``);
  const importWidth = Math.max(
    "Import shape".length,
    ...importCells.map((cell) => cell.length),
  );

  const lines = [
    SECTION_HEADING,
    "",
    "<!-- Generated by packages/components/scripts/generate-package-surface.mjs. Do not edit by hand. -->",
    "",
    `Counted from the entry lists in \`tsup.config.ts\`. Refresh with \`pnpm --filter ${PACKAGE_NAME} generate:surface\`.`,
    "",
    `| ${"Surface".padEnd(labelWidth)} | ${"Count".padEnd(countWidth)} | ${"Import shape".padEnd(importWidth)} |`,
    `| ${"-".repeat(labelWidth)} | ${`${"-".repeat(Math.max(countWidth - 1, 3))}:`.padStart(countWidth)} | ${"-".repeat(importWidth)} |`,
  ];

  surface.rows.forEach((row, index) => {
    lines.push(
      `| ${row.label.padEnd(labelWidth)} | ${String(row.count).padStart(countWidth)} | ${importCells[index].padEnd(importWidth)} |`,
    );
  });

  lines.push("", animatedOnlyParagraph(surface.animatedOnly));

  return `${lines.join("\n")}\n\n`;
}

/**
 * Splice a freshly rendered section into the README between its own heading and
 * the next one.
 *
 * @param {string} readme Current README text.
 * @param {string} section Rendered replacement section.
 * @returns {string} Updated README text.
 * @throws {Error} When either heading is missing.
 */
export function replacePackageSurfaceSection(readme, section) {
  const start = readme.indexOf(SECTION_HEADING);
  const end = readme.indexOf(NEXT_HEADING, start + SECTION_HEADING.length);
  if (start === -1 || end === -1) {
    throw new Error(
      `Could not find README section markers: "${SECTION_HEADING}" .. "${NEXT_HEADING}"`,
    );
  }
  return `${readme.slice(0, start)}${section}${readme.slice(end)}`;
}

/** @returns {string} README text with an up-to-date surface section. */
export function buildUpdatedReadme() {
  const readme = readFileSync(readmePath, "utf8");
  const section = renderPackageSurfaceSection(buildPackageSurface());
  return replacePackageSurfaceSection(readme, section);
}

/**
 * CLI entrypoint for `pnpm --filter @zentauri-ui/zentauri-components generate:surface`.
 *
 * @returns {void}
 */
function main() {
  const updated = buildUpdatedReadme();
  writeFileSync(readmePath, updated, "utf8");
  const surface = buildPackageSurface();
  console.log(
    `Updated package surface: ${surface.rows
      .map((row) => `${row.label.toLowerCase()} ${row.count}`)
      .join(", ")}.`,
  );
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
