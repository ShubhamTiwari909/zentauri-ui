import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tsupPath = join(root, "tsup.config.ts");
const outPath = join(root, "cli", "registry.json");

/**
 * Recursively reads every source file under `dir` and returns the concatenated
 * text. Returns "" if the directory does not exist. Used to detect which
 * optional peer dependencies a vendored component pulls in.
 */
function readTreeText(dir) {
  let out = "";
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return "";
  }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      out += readTreeText(p);
    } else if (/\.(tsx?|jsx?)$/.test(e.name) && !e.name.includes(".test.")) {
      out += readFileSync(p, "utf8");
    }
  }
  return out;
}

/**
 * Returns the optional peer dependencies a UI component folder imports.
 * `framer-motion` ships only inside `animated/` entries; `react-icons` and
 * `recharts` are detected from import specifiers anywhere in the tree.
 */
function detectUiPeerHints(componentName) {
  const dir = join(root, "src", "ui", componentName);
  const text = readTreeText(dir);
  const hints = [];
  if (/from\s+["']react-icons/.test(text)) hints.push("react-icons");
  if (/from\s+["']framer-motion/.test(text)) hints.push("framer-motion");
  if (/from\s+["']recharts/.test(text)) hints.push("recharts");
  return hints;
}

const text = readFileSync(tsupPath, "utf8");

function extractQuotedNames(block) {
  const names = [];
  const re = /["']([^"']+)["']/g;
  let m;
  while ((m = re.exec(block)) !== null) {
    names.push(m[1]);
  }
  return names;
}

const uiMatch = text.match(/const uiComponentNames = \[([\s\S]*?)\] as const/);
if (!uiMatch) {
  throw new Error("Could not parse uiComponentNames from tsup.config.ts");
}
const ui = extractQuotedNames(uiMatch[1]).sort();

const animatedMatch = text.match(
  /const uiAnimatedComponentNames = \[([\s\S]*?)\] as const/,
);
if (!animatedMatch) {
  throw new Error("Could not parse uiAnimatedComponentNames from tsup.config.ts");
}
const animated = extractQuotedNames(animatedMatch[1]).sort();

const chartsMatch = text.match(
  /const chartEntryNames = \[([\s\S]*?)\] as const/,
);
if (!chartsMatch) {
  throw new Error("Could not parse chartEntryNames from tsup.config.ts");
}
const charts = extractQuotedNames(chartsMatch[1]).map(
  (name) => `charts/${name}`,
);

const hooksMatch = text.match(
  /const hooksEntryNames = \[([\s\S]*?)\] as const/,
);
if (!hooksMatch) {
  throw new Error("Could not parse hooksEntryNames from tsup.config.ts");
}
const hooks = extractQuotedNames(hooksMatch[1]).sort();

// Optional peer dependencies, keyed by canonical component/chart name. Only
// entries with at least one optional peer are included. Consumed by the CLI to
// print install hints after vendoring.
const peerHints = {};
for (const name of new Set([...ui, ...animated])) {
  const hints = detectUiPeerHints(name);
  if (hints.length > 0) peerHints[name] = hints;
}
for (const chart of charts) {
  peerHints[chart] = ["recharts"];
}

const registry = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  description:
    "Addable UI components (src/ui), chart entries (src/charts/*), and hooks (src/hooks). Generated by scripts/generate-registry.mjs.",
  components: [...new Set([...ui, ...charts, ...animated])].sort(),
  hooks,
  peerHints,
  nameAliases: {
    button: "buttons",
    "chart-area": "charts/area",
    "chart-bar": "charts/bar",
    "chart-bubble": "charts/bubble",
    "chart-funnel": "charts/funnel",
    "chart-line": "charts/line",
    "chart-pie": "charts/pie",
    "chart-radar": "charts/radar",
    "chart-scatter": "charts/scatter",
    "chart-stacked-bar": "charts/stacked-bar",
    input: "inputs",
  },
};

writeFileSync(outPath, `${JSON.stringify(registry, null, 2)}\n`, "utf8");
console.log(
  `Wrote ${outPath} (${registry.components.length} components, ${registry.hooks.length} hooks)`,
);
